// --- Tool-texture visibility ------------------------------------------------
//
// Hammer's originals hide whole objects through auto visgroups; there is no
// per-face hide in CVisGroup. This port's View > Tool Textures menu is keyed on
// materials instead, which are a per-FACE property, so the semantics are:
//
//   * A face is hidden when its material normalizes to a "tools/" path that is
//     in the hidden set. Hidden faces are never drawn and never pickable, in
//     either the 2D or the 3D views (matching CMapDoc::SelectFace, which
//     refuses to pick faces the 3D view does not draw).
//   * A SOLID is hidden only when EVERY one of its faces is hidden. That is the
//     closest analogue to the original's whole-object visgroup hide: a solid
//     built entirely from a hidden tool material (a nodraw block, a trigger, a
//     clip brush) disappears and stops being selectable by click or box, while
//     a world brush that merely has nodraw on its back sides stays visible and
//     selectable in 2D and only loses those individual faces in 3D.
//   * Hidden solids are dropped from the selection when visibility changes,
//     mirroring CSelection::RemoveInvisibles.
bool isMaterialHiddenByToolTextures(std::string_view material,
                                    const std::unordered_set<std::string>& hiddenToolTextures);
bool isFaceHiddenByToolTextures(const FaceGeometry& face,
                                const std::unordered_set<std::string>& hiddenToolTextures);
bool isBrushHiddenByToolTextures(const BrushGeometry& brush,
                                 const std::unordered_set<std::string>& hiddenToolTextures);

// --- Billboarded sprite sizing ----------------------------------------------
//
// Single source of truth for the world-space size a point entity's sprite
