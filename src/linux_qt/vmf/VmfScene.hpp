struct DisplacementVertex
{
    Vec3 position{};
    // CCoreDispInfo::GenerateDispSurfNormals output. Source stores the averaged
    // normal without normalizing it a second time after CalcNormalFromEdges.
    Vec3 normal{0.0, 0.0, 1.0};
    // Source/Hammer CMapDisp render data generated by CalcDispSurfCoords and
    // GenerateDispSurfTangentSpaces. textureU/V remain in pre-normalized VMF
    // pixel space so render backends can divide by the loaded primary VTF size.
    double textureU{0.0};
    double textureV{0.0};
    Vec3 tangentS{1.0, 0.0, 0.0};
    Vec3 tangentT{0.0, 1.0, 0.0};
    // Source's VERTEXALPHATEXBLENDFACTOR receives 255 - CMapDisp::m_Alpha.
    double blendAlpha{0.0};
};

struct FaceGeometry
{
    int sideId{-1};
    std::string material;
    Vec3 normal{};
    TextureAxis uAxis{};
    TextureAxis vAxis{};
    // CMapFace::texture.nLightmapScale, the luxel size in world units. Hammer
    // defaults new faces to 16 (g_pGameConfig->GetDefaultLightmapScale()).
    int lightmapScale{16};
    std::vector<std::size_t> vertices;
    bool displacement{false};
    int displacementPower{0};
    std::vector<DisplacementVertex> displacementVertices;
    std::vector<std::size_t> displacementIndices;
};

struct BrushGeometry
{
    ObjectRef object;
    int id{-1};
    int ownerEntityId{-1};
    std::vector<Vec3> vertices;
    std::vector<std::pair<std::size_t, std::size_t>> edges;
    std::vector<FaceGeometry> faces;
    // Mirrors CMapSolid::HasDisp (hammer/mapsolid.cpp): true when ANY side of
    // this solid carries a dispinfo chunk.
    bool hasDisplacement{false};
};

// Hammer hides the non-displaced sides of a displacement solid in the 3D views.
// CMapSolid::Render3D computes
//     bMaskFaces = pDoc->IsDispSolidDrawMask() && HasDisp();
// and then skips every face for which !pFace->HasDisp(). CMapDoc::SelectFace
// applies the same mask so those hidden sides cannot be picked either. The
// toggle (CMapDoc::OnToggleDispSolidMask) defaults to true and only issues
// MAPVIEW_UPDATE_ONLY_3D, so the 2D wireframe views are deliberately unmasked.
bool isFaceMaskedByDisplacementSolid(const BrushGeometry& brush, const FaceGeometry& face,
                                     bool maskEnabled);



enum class ProjectedSurfaceKind { Decal, Overlay };

struct ProjectedSurfaceVertex
{
    Vec3 position{};
    Vec3 normal{0.0, 0.0, 1.0};
    double u{0.0};
    double v{0.0};
};

struct ProjectedSurface
{
    std::string material;
    ProjectedSurfaceKind kind{ProjectedSurfaceKind::Decal};
    // Triangle list. Every consecutive group of three vertices is one clipped
    // piece of the decal/overlay projected onto a brush or displacement face.
    std::vector<ProjectedSurfaceVertex> triangles;
};

struct EntityMarker
{
    ObjectRef object{ObjectType::Entity, -1};
    int id{-1};
    std::string classname;
    std::string targetName;
    Vec3 origin;
    Vec3 angles; // Raw Source pitch, yaw, roll from the VMF angles key
    bool hasPitchOverride{false};
    double pitchOverride{0.0};
    bool reversePitch{false}; // Exact Hammer lightprop render rule

    Vec3 renderAngles() const
    {
        Vec3 result = angles;
        if (hasPitchOverride) result.x = pitchOverride;
        if (reversePitch) result.x = -result.x;
        return result;
    }
    std::vector<std::pair<std::string, std::string>> properties;
    // Hammer stores info_overlay helper state in a nested overlaydata block.
    // Keep it separate from ordinary entity keyvalues so VMF properties remain
    // lossless while the renderer can consume the helper data directly.
    std::vector<std::pair<std::string, std::string>> overlayProperties;
    std::vector<ProjectedSurface> projectedSurfaces;
    // Solid ids whose faces the projected surfaces above were clipped onto.
    // Lets an incremental edit skip re-clipping entities whose source brushes
    // did not change (see projectedEntityDependsOnSolids).
    std::vector<int> projectedSourceSolidIds;
    Vec3 sizeMinimum{-8.0, -8.0, -8.0};
    Vec3 sizeMaximum{8.0, 8.0, 8.0};
    // World-space corners used for point-entity selection and transform handles.
    // Model helpers use transformed studio-model bounds; sprites use their image
    // dimensions; plain point entities fall back to the FGD size helper.
    std::array<Vec3, 8> selectionCorners{};
    bool hasSelectionCorners{false};
    std::array<int, 3> displayColor{108, 220, 108};
    std::string description;
    std::string model;
    int skin{0};
    // Source prop animation state. Sequence names are resolved lazily against
    // the cached MDL sequence table; a numeric sequence takes precedence.
    std::string animationSequence;
    int animationSequenceIndex{-1};
    double animationPlaybackRate{1.0};
    // A negative cycle means use the editor animation clock. A non-negative
    // value freezes the prop at that normalized sequence cycle.
    double animationCycle{-1.0};
    bool animateModel{false};
    std::string sprite;
};

