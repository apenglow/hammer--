struct Scene
{
    std::vector<BrushGeometry> brushes;
    std::vector<EntityMarker> entities;
    std::string skyName;
    // worldspawn "detailvbsp" and "detailmaterial": the detail-object
    // dictionary VBSP compiles this map's detail props from, and the material
    // whose atlas every detail sprite is cut out of. VBSP defaults the former
    // to "detail.vbsp" when the key is absent (FindDetailVBSPName).
    std::string detailVbspName;
    std::string detailMaterial;
    Vec3 minimum{};
    Vec3 maximum{};
    bool hasBounds{false};
    ToneMapSettings toneMap{};
    std::vector<ColorCorrectionDefinition> colorCorrections;

    // --- Incremental-update lineage --------------------------------------
    //
    // Render backends cache GPU buffers built from a Scene. Keying those caches
    // on the Scene's address is wrong twice over: a fresh Scene forces a full
    // re-upload even when one brush moved, and an in-place update reuses a
    // stale cache. These fields describe how this Scene differs from the one it
    // was derived from, so a backend can keep everything it already uploaded
    // and rebuild only the changed objects.
    //
    //   revision      unique, monotonically increasing id for this state.
    //   baseRevision  the revision this state was derived from, or 0 when the
    //                 scene was built from scratch (no reusable predecessor).
    //   changedSolidIds / changedEntityIds
    //                 exactly the objects that differ from baseRevision.
    std::uint64_t revision{0};
    std::uint64_t baseRevision{0};
    std::vector<int> changedSolidIds;
    std::vector<int> changedEntityIds;

    // Recent incremental steps, oldest first and bounded. Each entry records
    // the revision it advanced FROM and the objects that step changed. A
    // render cache whose revision matches any step's baseRevision can catch up
    // incrementally with the union of that step's and all later steps' ids -
    // essential when several edit steps land between two paints of a view
    // (every drag does this), which would otherwise fail the single-step
    // baseRevision check and force a full rebuild per frame.
    struct LineageStep
    {
        std::uint64_t baseRevision{0};
        std::vector<int> solidIds;
        std::vector<int> entityIds;
    };
    std::vector<LineageStep> lineageSteps;

    // Mark this state as having no reusable predecessor. Callers that mutate a
    // Scene outside rebuildSceneObjects (projected decal/overlay regeneration,
    // for instance) must call this so caches do a full rebuild.
    void invalidateLineage();
};

// Allocates the next process-wide unique Scene::revision.
std::uint64_t nextSceneRevision();

Scene buildScene(const Document& document);

// The geometry buildScene would produce for one "solid" block. Exposed so
// callers that already know which solids they care about (selection bounds,
// displacement painting) do not have to intersect the planes of every solid in
// the map to look at one of them.
BrushGeometry buildSolidGeometry(const Block& solid, int ownerEntityId = -1);

// buildScene restricted to the given solid ids: brushes are identical to the
// ones the full build would produce (including ownerEntityId and displacement
// tessellation) and everything else - entity markers, sky, tone map, color
// correction - is omitted. Scene bounds cover only the requested solids.
Scene buildSceneForSolids(const Document& document, const std::unordered_set<int>& solidIds);

// Fast path for interactive edits - dragging, resizing, rotating, displacement
// painting - which change a known set of objects and never create or destroy
// any. The listed solids and entity markers are rebuilt from the document and
// everything else is carried over from "previous", which for a drag of a few
// solids replaces a whole-map plane-intersection pass with a handful of solids.
//
// The result is what buildScene(document) would have returned. Whenever that
// cannot be guaranteed - an id is missing from the previous scene, a solid
// stopped forming a valid brush, or a changed entity feeds the scene-wide
// tone-map/color-correction state - this falls back to a full buildScene.
Scene rebuildSceneObjects(const Document& document, const Scene& previous,
                          const std::unordered_set<int>& changedSolidIds,
                          const std::unordered_set<int>& changedEntityIds);

// rebuildSceneObjects without the whole-scene copy: "scene" is updated in
// place and keeps its address, so a document that shares it with render
// backends does not have to hand out a new Scene per interactive edit. On
// success the scene's lineage records "scene.baseRevision" and the changed
// ids; on any fallback the scene is fully rebuilt and its lineage is cleared.
void rebuildSceneObjectsInPlace(const Document& document, Scene& scene,
                                const std::unordered_set<int>& changedSolidIds,
                                const std::unordered_set<int>& changedEntityIds);

